const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const stored = localStorage.getItem('epiwatch.lang');
    if (stored && STRINGS[stored]) return stored;
    return navigator.language?.startsWith('en') ? 'en' : 'fr';
  });

  useEffect(() => {
    localStorage.setItem('epiwatch.lang', lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback(
    (key, vars) => {
      const table = STRINGS[lang] || STRINGS.fr;
      let value = table[key] ?? STRINGS.fr[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          value = value.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        }
      }
      return value;
    },
    [lang],
  );

  const value = useMemo(
    () => ({ lang, setLang, t, languages: Object.values(LANGS) }),
    [lang, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n doit être utilisé dans un I18nProvider');
  return ctx;
}

/** Noms de maladies adaptés à la langue courante. */
export function diseaseName(disease, lang) {
  if (!disease) return '';
  return lang === 'en' ? disease.name_en || disease.name : disease.name;
}
